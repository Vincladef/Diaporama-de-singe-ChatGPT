import { useEffect, useLayoutEffect, useRef, useState, type PointerEvent, type MouseEvent } from "react";
import { createPortal } from "react-dom";
import type { SlideDocument, SlideElement } from "../domain/slide";
import { renderSlideHtml } from "../engine/render";
import { updateLiveSlideFrame } from "./liveSlideFrame";
import { elementBox, transformBox, withElementBoxes, worldBox, type Box, type TransformMode } from "./geometry";
import { FreeformOverlay, type FreeformHandle, type HtmlSelectionInfo } from "./FreeformOverlay";
import type { ShapePreset } from "./ShapePicker";
import { updateTextContent, type TextSelectionRange } from "./richText";

type Gesture = {
  pointerId: number;
  x: number;
  y: number;
  mode: TransformMode | "rotate";
  initial: Record<string, Box>;
  centerX?:number;centerY?:number;startAngle?:number;baseAngle?:number;latestAngle?:number;rotationId?:string;
  latest: Record<string, Box>;
  moved: boolean;
};
const handles: TransformMode[] = ["nw", "n", "ne", "e", "se", "s", "sw", "w"];
function getVisualLabel(e: SlideElement): string {
  return e.name || (e.type === "text" ? (e.text?.slice(0, 55) || "Texte vide") :
    e.type === "image" ? "Image" : e.type === "shape" ? "Forme" : e.type === "svg" ? "SVG" : "Groupe");
}
type Props = {
  document: SlideDocument;
  selectedIds: string[];
  onSelect: (ids: string[]) => void;
  onChange: (document: SlideDocument, key?: string) => void;
  zoom: number;
  grid: number;
  readOnly?: boolean;
  htmlControlRef?: {current:FreeformHandle|null};
  onHtmlSelectionChange?: (selection:HtmlSelectionInfo|null)=>void;
  onNativeRangeChange?: (range:TextSelectionRange|null)=>void;
  drawShape?:ShapePreset|null;
  onDrawShape?: (preset:ShapePreset,box:Box)=>void;
  onDrawFinished?:()=>void;
  onContextNativeAction?:(action:"duplicate"|"delete")=>void;
};

export function VisualCanvas({document: doc, selectedIds, onSelect, onChange, zoom, grid, readOnly,
  htmlControlRef,onHtmlSelectionChange,onNativeRangeChange,drawShape,onDrawShape,onDrawFinished,
  onContextNativeAction}: Props) {
  const wrapperRef = useRef<HTMLDivElement>(null);
  const frameRef = useRef<HTMLIFrameElement>(null);
  const freeRef = useRef<FreeformHandle>(null);
  const iframeReady=useRef(false);
  const initialMarkup=useRef(renderSlideHtml(doc));
  const [contextMenu,setContextMenu]=useState<{
    x:number;y:number;type:"native"|"html";ids:string[];
  }|null>(null);
  const [editingHtml,setEditingHtml]=useState(false);
  const [viewport, setViewport] = useState({width:840,height:460});
  const [live, setLive] = useState<Record<string, Box>>({});
  const [liveRotation,setLiveRotation]=useState<Record<string,string>>({});
  const [guides,setGuides]=useState<{x?:number;y?:number}>({});
  const [marquee,setMarquee]=useState<{x:number;y:number;w:number;h:number}|null>(null);
  const marqueeRef=useRef<{pointerId:number;x:number;y:number;shift:boolean;oldIds:string[]}|null>(null);
  const gesture = useRef<Gesture | null>(null);
  const [editId, setEditId] = useState<string | null>(null);
  const [editValue, setEditValue] = useState("");
  const documentRef = useRef(doc);
  documentRef.current = doc;
  const selectionRef = useRef(selectedIds);
  selectionRef.current = selectedIds;

  useEffect(() => {
    const div=wrapperRef.current;
    if (!div) return;
    const measure=()=>{
      const next={width:Math.max(1,div.clientWidth),height:Math.max(1,div.clientHeight)};
      setViewport(old=>old.width===next.width&&old.height===next.height?old:next);
    };
    measure();
    const observer=new ResizeObserver(measure);
    observer.observe(div);
    return ()=>observer.disconnect();
  },[]);
  useEffect(() => {
    gesture.current = null;
    setLive({});
    setLiveRotation({});
    setGuides({});
    setMarquee(null);
    marqueeRef.current=null;
    setEditId(null);
  },[doc.canvas.width,doc.canvas.height]);
  // Fit both dimensions, not only the width. The zoom multiplier is relative
  // to this contain scale, so the complete slide is visible by default.
  const contain=Math.min(Math.max(40,viewport.width-12)/doc.canvas.width,
    Math.max(40,viewport.height-24)/doc.canvas.height);
  const fit=Math.max(0.02,contain*zoom);
  const displayWidth=doc.canvas.width*fit;
  const displayHeight=doc.canvas.height*fit;
  // Keep the same iframe alive throughout editing. Only patch changed DOM nodes
  // (including HTML generated by AI). Full iframe loads occur on slide navigation.
  useLayoutEffect(()=>{
    if(!iframeReady.current)return;
    const frame=frameRef.current?.contentDocument;
    if(!frame?.body)return;
    updateLiveSlideFrame(frame,doc);
    freeRef.current?.refresh();
  },[doc]);

  useEffect(()=>{
    const close=()=>setContextMenu(null);
    const onKey=(event:KeyboardEvent)=>{if(event.key==="Escape")close();};
    window.addEventListener("pointerdown",close);
    window.addEventListener("scroll",close,true);
    window.addEventListener("keydown",onKey);
    return()=>{
      window.removeEventListener("pointerdown",close);
      window.removeEventListener("scroll",close,true);
      window.removeEventListener("keydown",onKey);
    };
  },[]);

  function openContextMenu(event:MouseEvent<HTMLDivElement>){
    if(readOnly||editingHtml)return;
    const target=event.target as HTMLElement;
    const native=target.closest<HTMLElement>("[data-visual-id]");
    const point=pointOnArtboard(event);
    let type:"native"|"html";
    let ids:string[]=[];
    if(native){
      const id=native.dataset.visualId;
      if(!id)return;
      type="native";
      ids=selectionRef.current.includes(id)?selectionRef.current:[id];
      if(!selectionRef.current.includes(id))onSelect(ids);
    }else if(freeRef.current?.selectForContext(point.x,point.y)){
      type="html";
    }else return;
    event.preventDefault();
    event.stopPropagation();
    setContextMenu({x:Math.max(8,Math.min(event.clientX,window.innerWidth-248)),
      y:Math.max(8,Math.min(event.clientY,window.innerHeight-298)),type,ids});
  }
  function menuAction(action:"front"|"back"|"forward"|"backward"|"duplicate"|"delete"){
    const menu=contextMenu;if(!menu)return;
    setContextMenu(null);
    if(menu.type==="html"){
      if(action==="duplicate")freeRef.current?.duplicate();
      else if(action==="delete")freeRef.current?.remove();
      else{
        const nodes=Array.from(frameRef.current?.contentDocument?.querySelectorAll<HTMLElement>("[data-id],[data-singe-id]")??[]);
        const levels=nodes.map(node=>parseInt(node.ownerDocument.defaultView?.getComputedStyle(node).zIndex??"",10)).filter(Number.isFinite);
        const values=levels.length?levels:[0];
        const current=freeRef.current?.currentLayer()??0;
        const z=action==="front"?Math.max(0,...values)+1:
          action==="back"?Math.min(0,...values)-1:
          action==="forward"?current+1:current-1;
        freeRef.current?.arrange(z);
      }
      return;
    }
    if(action==="duplicate"||action==="delete"){
      onContextNativeAction?.(action);return;
    }
    const frame=frameRef.current?.contentDocument;
    const nodes=Array.from(frame?.querySelectorAll<HTMLElement>("[data-id],[data-singe-id]")??[]);
    const levels=nodes.map(node=>parseInt(node.ownerDocument.defaultView?.getComputedStyle(node).zIndex??"",10)).filter(Number.isFinite);
    const values=levels.length?levels:[0];
    const active=doc.elements.find(e=>menu.ids.includes(e.id));
    const current=Number(active?.styles.zIndex??0)||0;
    const z=action==="front"?Math.max(0,...values)+1:
      action==="back"?Math.min(0,...values)-1:
      action==="forward"?current+1:current-1;
    const picked=new Set(menu.ids);
    onChange({...documentRef.current,elements:documentRef.current.elements.map(e=>
      picked.has(e.id)&&!e.locked?{...e,styles:{...e.styles,zIndex:z}}:e)},"layers");
  }

  function updateIframePreview(boxes: Record<string,Box>) {
    const frameDoc=frameRef.current?.contentDocument;
    if (!frameDoc) return;
    for (const [id, box] of Object.entries(boxes)) {
      const el=Array.from(frameDoc.querySelectorAll<HTMLElement>("[data-id]")).find(x=>x.dataset.id===id);
      if (!el) continue;
      const source=documentRef.current.elements.find(e=>e.id===id);
      const parent=source?.parentId ? documentRef.current.elements.find(e=>e.id===source.parentId) : undefined;
      const pb=parent ? worldBox(parent,documentRef.current) : {x:0,y:0,w:0,h:0};
      el.style.left=(box.x-pb.x)+"px";
      el.style.top=(box.y-pb.y)+"px";
      el.style.width=box.w+"px";
      el.style.height=box.h+"px";
    }
  }
  function begin(e: PointerEvent<HTMLElement>, id: string, mode: TransformMode | "rotate") {
    if (readOnly || editId || drawShape) return;
    const clicked=doc.elements.find(item=>item.id===id);
    if(!clicked||clicked.locked||clicked.hidden)return;
    if(clicked.linkFrom&&clicked.linkTo){onSelect([clicked.id]);return;}
    e.preventDefault();
    e.stopPropagation();
    wrapperRef.current?.focus({preventScroll:true});
    freeRef.current?.clear();onNativeRangeChange?.(null);
    const selected=selectionRef.current;
    const group=clicked.groupId && mode==="move"
      ?doc.elements.filter(item=>item.groupId===clicked.groupId&&!item.locked&&!item.hidden).map(item=>item.id)
      :[id];
    let ids:string[];
    if(e.shiftKey&&mode==="move"){
      ids=selected.includes(id)?selected.filter(x=>!group.includes(x)):[...new Set([...selected,...group])];
      onSelect(ids);
      if(!ids.includes(id))return;
    }else{
      ids=selected.includes(id)&&mode==="move"
        ?selected.filter(x=>!doc.elements.find(item=>item.id===x)?.locked)
        :group;
      if(ids.length!==selected.length||!ids.every((x,i)=>selected[i]===x))onSelect(ids);
    }
    const initial:Record<string,Box>={};
    for (const member of mode==="move" ? ids : [id]) {
      const element=doc.elements.find(x=>x.id===member);
      if (element) initial[member]=worldBox(element,doc);
    }
    const box=worldBox(clicked,doc);
    const artRect=wrapperRef.current?.querySelector(".visual-artboard")?.getBoundingClientRect();
    const centerX=(artRect?.left??0)+(box.x+box.w/2)*fit;
    const centerY=(artRect?.top??0)+(box.y+box.h/2)*fit;
    gesture.current={pointerId:e.pointerId,x:e.clientX,y:e.clientY,mode,initial,
      latest:initial,moved:false,centerX,centerY,rotationId:id,
      startAngle:Math.atan2(e.clientY-centerY,e.clientX-centerX)*180/Math.PI,
      baseAngle:parseFloat(String(clicked.styles.rotate??"0"))||0};
    e.currentTarget.setPointerCapture(e.pointerId);
  }
  function move(e: PointerEvent<HTMLElement>) {
    const g=gesture.current;
    if (!g || e.pointerId!==g.pointerId) return;
    e.preventDefault();
    if(g.mode==="rotate"){
      const angle=Math.atan2(e.clientY-(g.centerY??0),e.clientX-(g.centerX??0))*180/Math.PI;
      const value=Math.round(((g.baseAngle??0)+angle-(g.startAngle??0))*10)/10;
      if(!g.rotationId)return;
      g.latestAngle=value;g.moved=true;
      const rotateValue=value+"deg";
      setLiveRotation({[g.rotationId]:rotateValue});
      const el=Array.from(frameRef.current?.contentDocument?.querySelectorAll<HTMLElement>("[data-id]")??[])
        .find(x=>x.dataset.id===g.rotationId);
      if(el)el.style.rotate=rotateValue;
      return;
    }
    const dx=(e.clientX-g.x)/fit,dy=(e.clientY-g.y)/fit;
    if (Math.abs(dx)<.75 && Math.abs(dy)<.75 && !g.moved) return;
    const next:Record<string,Box>={};
    for (const [id,origin] of Object.entries(g.initial)) {
      next[id]=transformBox(origin,dx,dy,g.mode,grid);
    }
    const nextGuides:{x?:number;y?:number}={};
    if(g.mode==="move"){
      const ids=new Set(Object.keys(next));
      const moving=Object.values(next);
      const bounds={x:Math.min(...moving.map(b=>b.x)),y:Math.min(...moving.map(b=>b.y)),
        right:Math.max(...moving.map(b=>b.x+b.w)),bottom:Math.max(...moving.map(b=>b.y+b.h))};
      const mx=[bounds.x,(bounds.x+bounds.right)/2,bounds.right];
      const my=[bounds.y,(bounds.y+bounds.bottom)/2,bounds.bottom];
      let nearX=9,nearY=9,adjustX=0,adjustY=0;
      for(const item of doc.elements){
        if(ids.has(item.id)||item.hidden)continue;
        const other=worldBox(item,doc);
        for(const x of [other.x,other.x+other.w/2,other.x+other.w]){
          for(const pos of mx){
            const dist=x-pos;
            if(Math.abs(dist)<nearX){nearX=Math.abs(dist);adjustX=dist;nextGuides.x=x;}
          }
        }
        for(const y of [other.y,other.y+other.h/2,other.y+other.h]){
          for(const pos of my){
            const dist=y-pos;
            if(Math.abs(dist)<nearY){nearY=Math.abs(dist);adjustY=dist;nextGuides.y=y;}
          }
        }
      }
      if(nextGuides.x!==undefined||nextGuides.y!==undefined)
        for(const box of Object.values(next)){box.x+=adjustX;box.y+=adjustY;}
    }
    setGuides(nextGuides);
    g.latest=next;g.moved=true;
    updateIframePreview(next);
    setLive(next);
  }
  function end(e:PointerEvent<HTMLElement>) {
    const g=gesture.current;
    if (!g || e.pointerId!==g.pointerId) return;
    e.stopPropagation();
    gesture.current=null;
    if(g.moved){
      if(g.mode==="rotate"&&g.rotationId&&g.latestAngle!==undefined){
        const id=g.rotationId,rot=g.latestAngle+"deg";
        onChange({...documentRef.current,elements:documentRef.current.elements.map(element=>
          element.id===id?{...element,styles:{...element.styles,rotate:rot}}:element)},"rotate");
      }else onChange(withElementBoxes(documentRef.current,g.latest),"transform");
    }
    setLive({});
    setLiveRotation({});
    setGuides({});
    if (e.currentTarget.hasPointerCapture(e.pointerId)) e.currentTarget.releasePointerCapture(e.pointerId);
  }
  function pointOnArtboard(e:{clientX:number;clientY:number}){
    const rect=wrapperRef.current?.querySelector(".visual-artboard")?.getBoundingClientRect();
    return {x:(e.clientX-(rect?.left??0))/fit,y:(e.clientY-(rect?.top??0))/fit};
  }
  function startMarquee(e:PointerEvent<HTMLDivElement>){
    if(readOnly||editingHtml)return;
    e.preventDefault();
    wrapperRef.current?.focus({preventScroll:true});
    const point=pointOnArtboard(e);
    marqueeRef.current={pointerId:e.pointerId,x:point.x,y:point.y,shift:e.shiftKey,oldIds:selectionRef.current};
    e.currentTarget.setPointerCapture(e.pointerId);
    setMarquee(null);
  }
  function moveMarquee(e:PointerEvent<HTMLDivElement>){
    const start=marqueeRef.current;
    if(!start||e.pointerId!==start.pointerId)return;
    const p=pointOnArtboard(e);
    if(Math.abs(p.x-start.x)<6&&Math.abs(p.y-start.y)<6&&!marquee)return;
    setMarquee({x:Math.min(p.x,start.x),y:Math.min(p.y,start.y),
      w:Math.abs(p.x-start.x),h:Math.abs(p.y-start.y)});
  }
  function stopMarquee(e:PointerEvent<HTMLDivElement>){
    const start=marqueeRef.current;
    if(!start||e.pointerId!==start.pointerId)return;
    const p=pointOnArtboard(e);
    const rect={x:Math.min(p.x,start.x),y:Math.min(p.y,start.y),w:Math.abs(p.x-start.x),h:Math.abs(p.y-start.y)};
    marqueeRef.current=null;setMarquee(null);
    if(e.currentTarget.hasPointerCapture(e.pointerId))e.currentTarget.releasePointerCapture(e.pointerId);
    if(drawShape){
      if(rect.w>8&&rect.h>8)onDrawShape?.(drawShape,rect);
      onDrawFinished?.();return;
    }
    if(rect.w>6||rect.h>6){
      const picked=doc.elements.filter(el=>{
        if(el.hidden||el.locked)return false;
        const b=worldBox(el,doc);
        return b.x<rect.x+rect.w&&b.x+b.w>rect.x&&b.y<rect.y+rect.h&&b.y+b.h>rect.y;
      }).map(el=>el.id);
      onSelect(start.shift?[...new Set([...start.oldIds,...picked])]:picked);
      freeRef.current?.selectWithin(rect,start.shift);
    }else{
      if(!start.shift)onSelect([]);
      freeRef.current?.selectAt(p.x,p.y,start.shift);
    }
  }
  function beginInlineEdit(element: SlideElement) {
    if (readOnly || element.locked || element.hidden || element.type!=="text"&&element.type!=="shape") return;
    setEditId(element.id);
    setEditValue(element.text ?? "");
    onNativeRangeChange?.(null);
    onSelect([element.id]);
  }
  function commitInlineEdit() {
    const currentId=editId;
    if (!currentId) return;
    setEditId(null);
    const original=documentRef.current.elements.find(e=>e.id===currentId);
    if (original && editValue!==original.text) {
      onChange({...documentRef.current,elements:documentRef.current.elements.map(e=>e.id===currentId?updateTextContent(e,editValue):e)},"text");
    }
  }
  const chosen=doc.elements.find(e=>e.id===editId);
  const editBox=chosen && (live[chosen.id]??worldBox(chosen,doc));

  return (
    <>
    <div className={"visual-viewport"+(zoom>1?" is-zoomed":"")} ref={wrapperRef}
      aria-label="Surface d'édition graphique"
      tabIndex={-1}
      onContextMenu={openContextMenu}
      onPointerDown={e=>{
        if(readOnly||editingHtml)return;
        // The gray pasteboard is part of the editing surface: clicking it must
        // clear both native-object and freeform-HTML selections.
        if((e.target as HTMLElement).closest(".visual-artboard"))return;
        wrapperRef.current?.focus({preventScroll:true});
        onSelect([]);setEditId(null);freeRef.current?.clear();
      }}>
      <div className="visual-stage" style={{minWidth:Math.max(viewport.width,displayWidth+40),
        minHeight:Math.max(viewport.height,displayHeight+40)}}>
      <div className="visual-scale-bounds" style={{width:displayWidth,height:displayHeight}}>
      <div className="visual-ruler horizontal" aria-hidden="true" style={{width:displayWidth}}>
        {Array.from({length:Math.floor(doc.canvas.width/200)+1},(_,i)=>
          <span key={i} style={{left:i*200*fit}}>{i*200}</span>)}
      </div>
      <div className="visual-ruler vertical" aria-hidden="true" style={{height:displayHeight}}>
        {Array.from({length:Math.floor(doc.canvas.height/200)+1},(_,i)=>
          <span key={i} style={{top:i*200*fit}}>{i*200}</span>)}
      </div>
      <div className="visual-artboard" data-testid="visual-artboard" style={{
        width:doc.canvas.width,height:doc.canvas.height,
        transform:"scale("+fit+")",transformOrigin:"top left",
      }}>
        <iframe
          ref={frameRef}
          title="Aperçu sécurisé de la diapositive"
          sandbox="allow-same-origin"
          referrerPolicy="no-referrer"
          srcDoc={initialMarkup.current}
          onLoad={()=>{
            iframeReady.current=true;
            const frame=frameRef.current?.contentDocument;
            if(frame?.body)updateLiveSlideFrame(frame,documentRef.current);
            freeRef.current?.refresh();
          }}
          style={{position:"absolute",inset:0,border:0,width:doc.canvas.width,height:doc.canvas.height,pointerEvents:editingHtml?"auto":"none"}}
        />
        <div className={"visual-hit-layer"+(drawShape?" is-drawing":"")} style={{pointerEvents:editingHtml?"none":"auto",cursor:drawShape?"crosshair":"default"}}
          onPointerDown={startMarquee} onPointerMove={moveMarquee}
          onPointerUp={stopMarquee} onPointerCancel={stopMarquee}>
          {!readOnly && doc.elements.filter(el=>!el.parentId&&!el.hidden).concat(doc.elements.filter(el=>!!el.parentId&&!el.hidden)).map(element=>{
            const box=live[element.id]??worldBox(element,doc);
            const picked=selectedIds.includes(element.id);
            return (
              <div
                key={element.id}
                data-visual-id={element.id}
                className={"visual-object-hit"+(picked?" is-selected":"")}
                style={{left:box.x,top:box.y,width:box.w,height:box.h,pointerEvents:element.locked?"none":"auto",rotate:liveRotation[element.id]??String(element.styles.rotate??"0deg"),
                  zIndex:Number(element.styles.zIndex??0)}}
                title={getVisualLabel(element)}
                aria-label={getVisualLabel(element)}
                role="button" tabIndex={element.locked?-1:0} aria-pressed={picked}
                onKeyDown={e=>{
                  if(e.key==="Enter"||e.key===" "){e.preventDefault();e.stopPropagation();onSelect([element.id]);}
                }}
                onPointerDown={e=>begin(e,element.id,"move")}
                onPointerMove={move}
                onPointerUp={end}
                onPointerCancel={end}
                onDoubleClick={e=>{e.stopPropagation();beginInlineEdit(element);}}
              >
                {((element.type==="text"&&!element.text)||(element.type==="image"&&!element.src))&&
                  <span className="visual-empty-placeholder" aria-hidden="true">
                    {element.type==="image"?"Sélectionnez cette zone pour ajouter une image":
                     element.name?.includes("Titre")?"Cliquez pour ajouter un titre":"Cliquez pour ajouter du texte"}
                  </span>}
                {picked && <span className="visual-selection-name">{getVisualLabel(element).slice(0,32)}</span>}
                {picked && selectedIds.length===1 && handles.map(mode=>(
                  <span key={mode} data-handle={mode} className={"visual-resize-handle handle-"+mode}
                    onPointerDown={e=>begin(e,element.id,mode)}
                    onPointerMove={move}
                    onPointerUp={end}
                    onPointerCancel={end}
                    title={"Redimensionner "+mode}
                  />
                ))}
                {picked&&selectedIds.length===1&&<span className="visual-rotate-handle"
                  role="button" aria-label="Faire pivoter l'objet" title="Faire pivoter"
                  onPointerDown={e=>begin(e,element.id,"rotate")}
                  onPointerMove={move} onPointerUp={end} onPointerCancel={end}/>}
                
              </div>
            );
          })}
          {guides.x!==undefined&&<div className="visual-snap-guide vertical" style={{left:guides.x}}/>}
          {guides.y!==undefined&&<div className="visual-snap-guide horizontal" style={{top:guides.y}}/>}
          {marquee&&<div className="visual-marquee" style={{left:marquee.x,top:marquee.y,width:marquee.w,height:marquee.h}}/>}
          {!readOnly && <FreeformOverlay ref={node=>{freeRef.current=node;if(htmlControlRef)htmlControlRef.current=node;}}
            document={doc} frameRef={frameRef} scale={fit} grid={grid}
            onChange={onChange} onSelectStructured={onSelect} onSelectionChange={onHtmlSelectionChange}
            onMoveStructured={(base,dx,dy)=>{
              const changes:Record<string,Box>={};
              for(const id of selectionRef.current){
                const element=base.elements.find(e=>e.id===id&&!e.locked&&!e.hidden);
                if(element){const b=worldBox(element,base);changes[id]=transformBox(b,dx,dy,"move",0);}
              }
              return Object.keys(changes).length?withElementBoxes(base,changes):base;
            }}
            onEditingChange={setEditingHtml}/>}
          {!readOnly && editId && editBox && chosen && <textarea
            autoFocus
            data-testid="canvas-inline-text"
            className="visual-inline-text"
            style={{
              position:"absolute",left:editBox.x,top:editBox.y,width:editBox.w,height:Math.max(editBox.h,90),
              fontSize:elementBox(chosen,doc).h>0 ? (typeof chosen.styles.fontSize==="number" ? chosen.styles.fontSize+"px" : String(chosen.styles.fontSize??"64px")) : "64px",
              fontFamily:String(chosen.styles.fontFamily??"sans-serif"),
              fontWeight:String(chosen.styles.fontWeight??"normal"),
              color:String(chosen.styles.color??"#203127"),
              textAlign:(["left","center","right"].includes(String(chosen.styles.textAlign)) ? String(chosen.styles.textAlign) : "left") as "left" | "center" | "right",
            }}
            onPointerDown={e=>e.stopPropagation()}
            value={editValue} onChange={e=>setEditValue(e.target.value)}
            onSelect={e=>{const start=e.currentTarget.selectionStart,end=e.currentTarget.selectionEnd;
              if(end>start)onNativeRangeChange?.({id:chosen.id,start,end});}}
            onBlur={commitInlineEdit}
            onMouseUp={e=>{if(e.currentTarget.selectionStart===e.currentTarget.selectionEnd)
              onNativeRangeChange?.(null);}}
            onKeyDown={e=>{e.stopPropagation();if(e.key==="Escape"){setEditId(null);}if(e.key==="Enter"&&!e.shiftKey){e.preventDefault();commitInlineEdit();}}}
          />}
        </div>
      </div>
      </div>
      </div>
    </div>
    {contextMenu&&createPortal(
      <div className="singe-object-context-menu" role="menu" aria-label="Actions sur l’élément"
        style={{position:"fixed",left:contextMenu.x,top:contextMenu.y}}
        onPointerDown={e=>e.stopPropagation()} onContextMenu={e=>e.preventDefault()}>
        <div className="singe-object-context-caption">{contextMenu.type==="html"?"Élément HTML":"Objet sélectionné"}</div>
        <button role="menuitem" onClick={()=>menuAction("front")}>Mettre au premier plan</button>
        <button role="menuitem" onClick={()=>menuAction("forward")}>Avancer d’un niveau</button>
        <button role="menuitem" onClick={()=>menuAction("backward")}>Reculer d’un niveau</button>
        <button role="menuitem" onClick={()=>menuAction("back")}>Mettre à l’arrière-plan</button>
        <div className="singe-object-context-separator"/>
        <button role="menuitem" onClick={()=>menuAction("duplicate")}>Dupliquer</button>
        <button role="menuitem" className="danger" onClick={()=>menuAction("delete")}>Supprimer</button>
      </div>,document.body)}
    </>
  );
}
