import JSZip from "jszip";
import type { SlideDocument, AnimationStep } from "../domain/slide.ts";
import { buildPlaybackPlan } from "../animation/timeline.ts";
import { isNativePptxObject } from "./preflight.ts";

const supported = new Set<AnimationStep["effect"]>(["appear","fade","move","scale","wipe"]);
type Preset = { id: number; subtype: number; filter?: string; options?: string };
const presets: Record<string, Preset> = {
  appear: {id:1, subtype:0},
  fade: {id:10, subtype:0, filter:"fade"},
  move: {id:2, subtype:4, filter:"slide(fromBottom)"},
  scale: {id:23, subtype:0, filter:"image",options:"in"},
  wipe: {id:22, subtype:1, filter:"wipe(left)"},
};

function targetId(step: AnimationStep): string | null {
  if(step.targetElementId) return step.targetElementId;
  const sel=step.targetSelector?.trim();
  if(!sel) return null;
  const data=sel.match(/^\[data-id=["']([^"']{1,128})["']\]$/);
  if(data)return data[1]!;
  const simple=sel.match(/^#([A-Za-z][A-Za-z0-9_-]{0,127})$/);
  return simple?.[1]??null;
}

/** Only native objects can receive Office animations; arbitrary HTML/CSS is
 * exported as progressive frames until a safe element-level conversion exists.
 */
export function canUseNativeAnimations(doc: SlideDocument): boolean {
  if(!doc.animations.length || doc.mode==="freeform" ||
    doc.elements.some(el=>!isNativePptxObject(el))) return false;
  const eligible=new Set(doc.elements.filter(el=>el.type!=="group" &&
    (el.type!=="image" || Boolean(el.src)) &&
    !(el.type==="shape" && /^linear-gradient\\(/i.test(String(el.styles.background??el.styles.backgroundColor??"")))
  ).map(el=>el.id));
  return doc.animations.every(step=>{
    const id=targetId(step);
    return Boolean(id&&eligible.has(id)&&supported.has(step.effect));
  });
}

function decodeXmlAttr(s:string):string {
  return s.replace(/&quot;/g,'"').replace(/&apos;/g,"'")
    .replace(/&amp;/g,"&").replace(/&lt;/g,"<").replace(/&gt;/g,">");
}

/** Reads only shape IDs generated by PptxGenJS; no arbitrary XML is evaluated. */
export function readNativeShapeIds(xml:string):Map<string,number> {
  const ids=new Map<string,number>();
  for(const match of xml.matchAll(/<p:cNvPr\b([^>]*?)(?:\/>|>)/g)){
    const id=match[1]!.match(/\bid="(\d+)"/);
    const name=match[1]!.match(/\bname="([^"]*)"/);
    if(id&&name)ids.set(decodeXmlAttr(name[1]!),Number(id[1]));
  }
  return ids;
}

/** Each click becomes a real PowerPoint timing event, not a new slide.
 * The animation presets follow ISO/IEC 29500 PresentationML.
 */
export function buildNativeTimingXml(xml:string,doc:SlideDocument):string {
  if(!canUseNativeAnimations(doc))throw new Error("La diapositive ne possède pas d'objets animables natifs.");
  if(/<p:timing\b/.test(xml))throw new Error("La diapositive possède déjà une chronologie PowerPoint.");
  const idMap=readNativeShapeIds(xml);
  const plan=buildPlaybackPlan(doc.animations);
  let n=2;
  const next=()=>++n;
  const effect=(cue:AnimationStep,nodeType:"clickEffect"|"afterEffect"|"withEffect"):string=>{
    const name=targetId(cue);
    const id=name?idMap.get(name):undefined;
    if(id===undefined)throw new Error("Objet PowerPoint introuvable pour l'animation : "+(name??cue.id));
    const def=presets[cue.effect]!;
    const duration=Math.max(1,Math.min(60000,cue.durationMs));
    const effectType=cue.effect==="appear"?"appear":cue.effect;
    const setId=next();
    const set= '<p:set><p:cBhvr><p:cTn id="'+setId+'" dur="1" fill="hold"/>'+
      '<p:tgtEl><p:spTgt spid="'+id+'"/></p:tgtEl>'+
      '<p:attrNameLst><p:attrName>style.visibility</p:attrName></p:attrNameLst>'+
      '</p:cBhvr><p:to><p:strVal val="visible"/></p:to></p:set>';
    let behavior="";
    if(def.filter){
      const behaviorId=next();
      behavior='<p:animEffect transition="in" filter="'+def.filter+'"'+
        (def.options?' prLst="'+def.options+'"':'')+'>'+
        '<p:cBhvr><p:cTn id="'+behaviorId+'" dur="'+duration+'"/>'+
        '<p:tgtEl><p:spTgt spid="'+id+'"/></p:tgtEl></p:cBhvr></p:animEffect>';
    }
    const idNode=next();
    return '<p:par><p:cTn id="'+idNode+'" presetID="'+def.id+
      '" presetClass="entr" presetSubtype="'+def.subtype+
      '" fill="hold" grpId="0" nodeType="'+nodeType+'">'+
      '<p:stCondLst><p:cond delay="'+(cue.delayMs??0)+'"/></p:stCondLst>'+
      '<p:childTnLst>'+set+behavior+'</p:childTnLst>'+
      '</p:cTn></p:par>';
  };
  const group=(cues:AnimationStep[],clicked:boolean):string=>{
    if(!cues.length)return "";
    const entries=cues.map((cue,i)=>effect(cue,clicked?(i===0?"clickEffect":"afterEffect"):"withEffect")).join("");
    const eventId=next();
    return '<p:par><p:cTn id="'+eventId+'" fill="hold">'+
      '<p:stCondLst><p:cond delay="'+(clicked?'indefinite':'0')+'"/></p:stCondLst>'+
      '<p:childTnLst>'+entries+'</p:childTnLst></p:cTn></p:par>';
  };
  const entries=group(plan.intro,false)+plan.clicks.map(click=>group(click,true)).join("");
  const timing='<p:timing><p:tnLst><p:par>'+
    '<p:cTn id="1" dur="indefinite" restart="never" nodeType="tmRoot"><p:childTnLst>'+
    '<p:seq concurrent="1" nextAc="seek"><p:cTn id="2" dur="indefinite" nodeType="mainSeq">'+
    '<p:childTnLst>'+entries+'</p:childTnLst></p:cTn>'+
    '<p:prevCondLst><p:cond evt="onPrev" delay="0"><p:tgtEl><p:sldTgt/></p:tgtEl></p:cond></p:prevCondLst>'+
    '<p:nextCondLst><p:cond evt="onNext" delay="0"><p:tgtEl><p:sldTgt/></p:tgtEl></p:cond></p:nextCondLst>'+
    '</p:seq></p:childTnLst></p:cTn></p:par></p:tnLst></p:timing>';
  const at=xml.lastIndexOf("</p:sld>");
  if(at<0)throw new Error("Document XML PowerPoint invalide.");
  return xml.slice(0,at)+timing+xml.slice(at);
}

export async function addNativeAnimationsToPptx(
  original:Blob,
  documents: {index:number;document:SlideDocument}[],
):Promise<Blob> {
  if(!documents.length)return original;
  const zip=await JSZip.loadAsync(original);
  for(const {index,document} of documents){
    if(!canUseNativeAnimations(document))continue;
    const path="ppt/slides/slide"+(index+1)+".xml";
    const file=zip.file(path);
    if(!file)throw new Error("XML de la diapositive "+(index+1)+" introuvable.");
    zip.file(path,buildNativeTimingXml(await file.async("string"),document));
  }
  const data=await zip.generateAsync({type:"uint8array",compression:"DEFLATE"});
  return new Blob([new Uint8Array(data)],{type:"application/vnd.openxmlformats-officedocument.presentationml.presentation"});
}
